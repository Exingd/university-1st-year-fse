a = int(input('Введите первую координату первой клетки (число от 1 до 8): '))
b = int(input('Введите вторую координату первой клетки (число от 1 до 8): '))
c = int(input('Введите первую координату второй клетки (число от 1 до 8): '))
d = int(input('Введите вторую координату второй клетки (число от 1 до 8): '))
e = a + b
f = c + d
if a > 8 or b > 8 or c > 8 or d > 8:
    print('Введено слишком большое значение')
else:
    if e % 2 == 0 and f % 2 == 0:
        print('YES, WHITE')
    elif e % 2 == 1 and f % 2 == 1:
        print('YES, BLACK')
    else:
        print('NO')
